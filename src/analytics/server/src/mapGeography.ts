function normalizeSubdivision(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replaceAll(String.fromCharCode(248), 'o')
    .replaceAll(String.fromCharCode(230), 'ae')
    .replaceAll(String.fromCharCode(223), 'ss')
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

export function getSubdivisionKey(country: string, subdivision: string): string {
  return country.toUpperCase() + '|' + normalizeSubdivision(subdivision);
}

export function getSubdivisionCenter(country: string, subdivision: string): MapCoordinates | null {
  return subdivisionCenters[getSubdivisionKey(country, subdivision)] ?? null;
}
